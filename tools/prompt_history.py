#!/usr/bin/env python3
"""Keep a record of every released recurring-task prompt, so a task can be checked
for customer changes before it is updated automatically.

    python3 tools/prompt_history.py           # add the current templates if their version is missing
    python3 tools/prompt_history.py --check   # fail if the current templates aren't recorded exactly

The history lives at skills/schedule-workforce/references/prompt-history.md and is
synced into the skills that update their own tasks.
"""
import re, sys, subprocess, hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFS = ROOT / "plugins/ai-workforce/skills/schedule-workforce/references"
PROMPTS, HISTORY = REFS / "scheduled-prompts.md", REFS / "prompt-history.md"
STANDARD = ["daily-executive-briefing", "inbox-triage", "prepare-weekly-marketing", "review-overdue-invoices"]
HEADER = """# Released recurring-task instructions (for safe automatic updates)

Every version of the standard recurring-task instructions the plugin has released, exactly as released. A task may be updated automatically only if its current instructions are **exactly** one of these (with the Business Brain's page title in place of `<BRAIN>`; line endings and spaces at the ends of lines may differ, nothing else). Anything else, including an older task with no version line, counts as customized: don't overwrite it; ask the owner (`references/run-modes.md`, "Keep the task up to date automatically").

Each entry also says what that version needs: the Business Brain version and the connections it uses. Generated by `tools/prompt_history.py`; never edit by hand.
"""
# Minimum Business Brain version each prompt version relies on. Every released prompt version needs an entry.
NEEDS = {"0.5.0": "0.5.0", "0.5.1": "0.5.0", "0.5.2": "0.5.0"}
CONNECTIONS = {  # what each task uses (only apps named in Workforce Settings; missing ones fall back to the Paste Box)
    "daily-executive-briefing": "Notion; email, calendar and files if connected",
    "inbox-triage": "Notion; email if connected",
    "prepare-weekly-marketing": "Notion; files if connected",
    "review-overdue-invoices": "Notion; files if connected",
}
# Seed only from commits that were actually published (pushed): 64e4dd6 (0.5.0), bb1e466 (0.5.1), 8ca2289 (0.5.2).

def templates(text):
    out = {}
    for b in re.findall(r"```\n(.*?)```", text, re.S):
        m = re.match(r"\[AI Workforce task: ([a-z-]+) \| prompt version ([0-9.]+)\]", b)
        if m and m.group(1) in STANDARD:
            out[(m.group(1), m.group(2))] = b.rstrip("\n")
    return out

def digest(text):
    return hashlib.sha256(text.encode()).hexdigest()[:16]

def recorded(text, verify=False):
    out = {}
    for m in re.finditer(r"^## ([a-z-]+) ([0-9.]+)\nNeeds:.*?Fingerprint: ([0-9a-f]+)\.\n\n````text\n(.*?)\n````", text, re.S | re.M):
        key, fp, body = (m.group(1), m.group(2)), m.group(3), m.group(4)
        if verify and digest(body) != fp:
            sys.exit(f"{key[0]} {key[1]}: recorded text was edited after release")
        out[key] = body
    return out

def render(entries):
    parts = [HEADER]
    for (skill, ver) in sorted(entries, key=lambda k: (STANDARD.index(k[0]), [int(x) for x in k[1].split(".")])):
        if ver not in NEEDS:
            sys.exit(f"add a NEEDS entry for prompt version {ver}")
        body = entries[(skill, ver)]
        parts.append(f"## {skill} {ver}\nNeeds: Business Brain version {NEEDS[ver]} or later; connections: {CONNECTIONS[skill]}. Fingerprint: {digest(body)}.\n\n````text\n{body}\n````\n")
    return "\n".join(parts)

def main(check):
    current = templates(PROMPTS.read_text())
    if sorted(k[0] for k in current) != sorted(STANDARD):
        sys.exit(f"expected one current template for each of {STANDARD}, found {sorted(current)}")
    have = recorded(HISTORY.read_text(), verify=check) if HISTORY.exists() else {}
    if check:
        if HISTORY.read_text() != render(have):
            sys.exit("prompt-history.md differs from what the tool generates: regenerate it")
        bad = [f"{k[0]} {k[1]}" for k, v in current.items() if have.get(k) != v]
        print("\n".join(f"not recorded exactly: {b}" for b in bad) or "Prompt history up to date.")
        sys.exit(1 if bad else 0)
    if "--seed" in sys.argv:  # only commits that were published  # add released versions from git history
        for rev in sys.argv[sys.argv.index("--seed") + 1:]:
            old = subprocess.run(["git", "show", f"{rev}:plugins/ai-workforce/skills/schedule-workforce/references/scheduled-prompts.md"],
                                 capture_output=True, text=True, cwd=ROOT, check=True).stdout
            for k, v in templates(old).items():
                have.setdefault(k, v)
    for k, v in current.items():
        if k in have and have[k] != v:
            sys.exit(f"{k[0]} {k[1]} changed but its version didn't: raise the prompt version first")
        have.setdefault(k, v)
    HISTORY.write_text(render(have))
    print(f"Recorded {len(have)} templates.")

if __name__ == "__main__":
    main("--check" in sys.argv)
