#!/usr/bin/env python3
"""Keep a record of every released recurring-task prompt, so a task can be checked
for customer changes before it is updated automatically.

    python3 tools/prompt_history.py           # record the current templates if their version is missing
    python3 tools/prompt_history.py --check   # fail if anything isn't recorded exactly

Two files:
- tools/released-prompts.md (maintainers only, not shipped): every released prompt, word for word.
- skills/schedule-workforce/references/prompt-history.md (shipped, synced into the skills that update
  their own tasks): one fingerprint per released version. A run compares the task's fingerprint with
  this table instead of reading every old prompt, which keeps scheduled runs cheap.

The fingerprint recipe below must stay identical to the script in run-modes.md
("Is the recurring task current?"); a test runs that script against this table.
"""
import re, sys, subprocess, hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFS = ROOT / "plugins/ai-workforce/skills/schedule-workforce/references"
PROMPTS, TABLE = REFS / "scheduled-prompts.md", REFS / "prompt-history.md"
ARCHIVE = ROOT / "tools" / "released-prompts.md"
STANDARD = ["daily-executive-briefing", "inbox-triage", "prepare-weekly-marketing", "review-overdue-invoices"]
ARCHIVE_HEADER = """# Released recurring-task instructions (maintainers only)

Every version of the standard recurring-task instructions the plugin has released, exactly as released. This file is not shipped in the plugin: runs compare fingerprints with `prompt-history.md` instead. Generated by `tools/prompt_history.py`; never edit by hand.
"""
TABLE_HEADER = """# Released recurring-task instructions: fingerprints

One line per released version of each standard recurring task's stored instructions. A task may be updated automatically only if its fingerprint (computed with the script in `references/run-modes.md`, "Is the recurring task current?") is in this table for its responsibility. Anything else, including an older task with no version line, counts as customized: don't overwrite it. "Needs" is what that version relies on: the Business Brain version and the connections it uses. Generated by `tools/prompt_history.py`; never edit by hand.

| Responsibility | Prompt version | Fingerprint | Needs |
|---|---|---|---|
"""
# Minimum Business Brain version each prompt version relies on. Every released prompt version needs an entry.
NEEDS = {"0.5.0": "0.5.0", "0.5.1": "0.5.0", "0.5.2": "0.5.0", "0.5.4": "0.5.0", "0.7.0": "0.5.0"}
CONNECTIONS = {  # what each task uses (only apps named in Workforce Settings; missing ones fall back to the Paste Box)
    "daily-executive-briefing": "Notion; email, calendar and files if connected",
    "inbox-triage": "Notion; email if connected",
    "prepare-weekly-marketing": "Notion; files if connected",
    "review-overdue-invoices": "Notion; files if connected",
}
# Seeded only from commits that were actually published (pushed): 64e4dd6 (0.5.0), bb1e466 (0.5.1), 8ca2289 (0.5.2).

def fingerprint(text):
    """Same steps as the run-modes.md script: CRLF -> LF, cut at "Owner's additions",
    the Business Brain title back to <BRAIN>, trailing spaces off, sha256, first 16 hex."""
    t = text.replace("\r\n", "\n")
    t = re.split(r"(?m)^Owner's additions\b", t)[0]
    t = re.sub(r'titled exactly "[^"\n]*"', 'titled exactly "<BRAIN>"', t)
    t = "\n".join(l.rstrip() for l in t.split("\n")).strip()
    return hashlib.sha256(t.encode("utf-8")).hexdigest()[:16]

def templates(text):
    out = {}
    for b in re.findall(r"```\n(.*?)```", text, re.S):
        m = re.match(r"\[AI Workforce task: ([a-z-]+) \| prompt version ([0-9.]+)\]", b)
        if m and m.group(1) in STANDARD:
            out[(m.group(1), m.group(2))] = b.rstrip("\n")
    return out

def recorded(text, verify=False):
    out = {}
    for m in re.finditer(r"^## ([a-z-]+) ([0-9.]+)\nNeeds:.*?Fingerprint: ([0-9a-f]+)\.\n\n````text\n(.*?)\n````", text, re.S | re.M):
        key, fp, body = (m.group(1), m.group(2)), m.group(3), m.group(4)
        if verify and fingerprint(body) != fp:
            sys.exit(f"{key[0]} {key[1]}: recorded text was edited after release")
        out[key] = body
    return out

def order(entries):
    return sorted(entries, key=lambda k: (STANDARD.index(k[0]), [int(x) for x in k[1].split(".")]))

def needs(skill, ver):
    if ver not in NEEDS:
        sys.exit(f"add a NEEDS entry for prompt version {ver}")
    return f"Business Brain version {NEEDS[ver]} or later; connections: {CONNECTIONS[skill]}"

def render_archive(entries):
    parts = [ARCHIVE_HEADER]
    for (skill, ver) in order(entries):
        body = entries[(skill, ver)]
        parts.append(f"## {skill} {ver}\nNeeds: {needs(skill, ver)}. Fingerprint: {fingerprint(body)}.\n\n````text\n{body}\n````\n")
    return "\n".join(parts)

def render_table(entries):
    rows = [f"| {s} | {v} | {fingerprint(entries[(s, v)])} | {needs(s, v)} |" for (s, v) in order(entries)]
    return TABLE_HEADER + "\n".join(rows) + "\n"

def main(check):
    current = templates(PROMPTS.read_text())
    if sorted(k[0] for k in current) != sorted(STANDARD):
        sys.exit(f"expected one current template for each of {STANDARD}, found {sorted(current)}")
    have = recorded(ARCHIVE.read_text(), verify=check) if ARCHIVE.exists() else {}
    if check:
        problems = []
        if ARCHIVE.read_text() != render_archive(have):
            problems.append("tools/released-prompts.md differs from what the tool generates: regenerate it")
        if not TABLE.exists() or TABLE.read_text() != render_table(have):
            problems.append("prompt-history.md differs from what the tool generates: regenerate it")
        problems += [f"not recorded exactly: {k[0]} {k[1]}" for k, v in current.items() if have.get(k) != v]
        print("\n".join(problems) or "Prompt history up to date.")
        sys.exit(1 if problems else 0)
    if "--seed" in sys.argv:  # add released versions from git history (only commits that were published)
        for rev in sys.argv[sys.argv.index("--seed") + 1:]:
            old = subprocess.run(["git", "show", f"{rev}:plugins/ai-workforce/skills/schedule-workforce/references/scheduled-prompts.md"],
                                 capture_output=True, text=True, cwd=ROOT, check=True).stdout
            for k, v in templates(old).items():
                have.setdefault(k, v)
    for k, v in current.items():
        if k in have and have[k] != v:
            sys.exit(f"{k[0]} {k[1]} changed but its version didn't: raise the prompt version first")
        have.setdefault(k, v)
    ARCHIVE.write_text(render_archive(have))
    TABLE.write_text(render_table(have))
    print(f"Recorded {len(have)} templates.")

if __name__ == "__main__":
    main("--check" in sys.argv)
